export const LANG_STORAGE_KEY = "fit-reader.lang";

let lang = "zh";

export const getLang = () => lang;
export const setLang = (l) => {
  lang = l === "en" ? "en" : "zh";
  document.documentElement?.setAttribute("lang", lang);
  return lang;
};

/** 首次启动检测：浏览器系统语言为中文 → zh，其余一律 en */
export function detectLang() {
  const nav = navigator.language || (navigator.languages && navigator.languages[0]) || "";
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export const getStoredLang = () => localStorage.getItem(LANG_STORAGE_KEY);
export const setStoredLang = (l) => localStorage.setItem(LANG_STORAGE_KEY, l === "en" ? "en" : "zh");

