/** TSB 状态简评（与 db.js formNote 同口径；详情页优先用服务端 form_state 本地化文本） */
export function formNote(tsb) {
  if (tsb >= 15) return t("form.note.0");
  if (tsb >= 5) return t("form.note.1");
  if (tsb >= -10) return t("form.note.2");
  if (tsb >= -20) return t("form.note.3");
  return t("form.note.4");
}

