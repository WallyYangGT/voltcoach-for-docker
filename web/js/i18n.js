/** 按当前语言取文案并做 {var} 插值；未知 key 回落 zh / 原 key */
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(v == null ? "" : String(v));
    }
  }
  return s;
}

